#!/usr/bin/env python3
# Generates main/model_table.h from Google Play supported_devices.csv (UTF-16).
# Usage: python3 tools/gen_model_table.py <supported_devices.csv> <out.h>
import csv, io, sys, collections
src, out = sys.argv[1], sys.argv[2]
txt = open(src, "rb").read().decode("utf-16")
rows = list(csv.reader(io.StringIO(txt)))[1:]
BR = {"samsung":"Samsung","xiaomi":"Xiaomi","redmi":"Xiaomi","poco":"Xiaomi","oppo":"OPPO","realme":"realme",
      "vivo":"vivo","infinix":"Infinix","tecno":"Tecno","itel":"itel","motorola":"Motorola","oneplus":"OnePlus",
      "huawei":"Huawei","honor":"Honor","google":"Google","nokia":"Nokia","hmd global":"Nokia"}
def ascii_ok(s): return all(0x20 <= ord(c) <= 0x7E for c in s)
cnt = collections.defaultdict(collections.Counter)
for r in rows:
    if len(r) < 4: continue
    b = BR.get(r[0].strip().lower())
    name, model = r[1].strip(), r[3].strip()
    if not b or not name or not model: continue
    if not (ascii_ok(name) and ascii_ok(model)): continue
    if len(model) > 31 or len(name) > 40: continue
    if name.isdigit() or name.lower() == model.lower(): continue
    cnt[model.lower()][(b, name)] += 1
brands = [""] + sorted(set(b for c in cnt.values() for (b, _) in c))
bidx = {b: i for i, b in enumerate(brands)}
entries = []
for k in sorted(cnt):
    (b, name), _ = cnt[k].most_common(1)[0]
    entries.append((k, b, name))
def cesc(s): return s.replace("\\", "\\\\").replace('"', '\\"')
offs, lines, pos = [], [], 0
for k, b, name in entries:
    offs.append(pos)
    lines.append('"\\%03o%s\\0%s\\0"' % (bidx[b], cesc(k), cesc(name)))
    pos += 1 + len(k) + 1 + len(name) + 1
with open(out, "w") as f:
    f.write("/* Auto-generated by tools/gen_model_table.py from Google Play supported_devices.csv. Do not edit by hand. */\n")
    f.write("#pragma once\n#include <stdint.h>\n")
    f.write("static const char *const MODEL_BRANDS[] = {%s};\n" % ",".join('"%s"' % x for x in brands))
    f.write("#define MODEL_COUNT %d\n" % len(entries))
    f.write("static const char MODEL_BLOB[] =\n" + "\n".join(lines) + ";\n")
    f.write("static const uint32_t MODEL_OFF[MODEL_COUNT] = {%s};\n" % ",".join(str(o) for o in offs))
per = collections.Counter(b for _, b, _ in entries)
print("entries:", len(entries), "| blob bytes:", pos, "| offsets bytes:", 4 * len(entries), "| total ~", pos + 4 * len(entries))
print("per brand:", dict(per))
